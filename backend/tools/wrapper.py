"""Deterministic BenchDataset wrapper generation.

Template fill — every BandSpec number comes straight from measured stats, so
the emitted file is guaranteed-valid Python with correct values. Claude only
writes the human-facing note.
"""

from __future__ import annotations

import keyword
import re

from schemas import Inspection, Wrapper

_TEMPLATE = '''"""Auto-generated torchgeo-bench wrapper for {dataset_name}.

Generated by GeoBench Copilot from an uploaded archive:
{chips} chips, {n_bands} band(s), dtype {dtype}, structure: {structure}.
Per-band statistics measured on a fixed-seed sample of the uploaded chips.
{split_comment}
Place this file at src/torchgeo_bench/datasets/{module_name}.py and register
{class_name} in datasets/loading.py, then put your extracted archive under
data/{dataset_name}/.
"""

from pathlib import Path

import numpy as np
import torch
from torch.utils.data import Dataset

from .base import BandSpec, BenchDataset

_IMAGE_EXTS = {{".tif", ".tiff", ".png", ".jpg", ".jpeg"}}


class _FolderDataset(Dataset):
    """Reads a {{split}}/{{class}}/chip.tif (or {{class}}/chip.tif) layout.

    Emits raw float32 pixel values — normalization is the model's job,
    matching the BenchDataset contract.
    """

    def __init__(self, root: Path, split: str, classes: list[str], transform=None):
        import hashlib
        import json

        self.transform = transform
        self.classes = classes

        # Gather candidate samples. If explicit {{split}}/ subfolders exist,
        # scope to this split; otherwise read the flat class folders and
        # partition below.
        split_dir = root / split
        scoped = split_dir.is_dir()
        base = split_dir if scoped else root
        samples: list[tuple[Path, int]] = []
        for idx, cls in enumerate(classes):
            for p in sorted((base / cls).glob("*")):
                if p.suffix.lower() in _IMAGE_EXTS:
                    samples.append((p, idx))

        if scoped:
            self.samples = samples
            return

        # No split subfolders. Prefer a splits.json manifest
        # (filename -> "train"/"val"/"test"), which GeoBench Copilot writes for
        # auto-fetched chips using a SPATIAL-BLOCK split so overlapping chips
        # never straddle splits. Otherwise fall back to a stable-hash 80/10/10
        # (hashlib, not the salted builtin hash(), so it's reproducible across
        # runs — and every split is partitioned, so train no longer gets all).
        manifest = root / "splits.json"
        if manifest.is_file():
            mapping = json.loads(manifest.read_text())
            self.samples = [s for s in samples if mapping.get(s[0].name) == split]
            return

        def _bucket(name: str) -> int:
            return int.from_bytes(hashlib.sha1(name.encode()).digest()[:4], "big") % 10

        lo, hi = {{"train": (0, 8), "val": (8, 9), "test": (9, 10)}}[split]
        self.samples = [s for s in samples if lo <= _bucket(s[0].name) < hi]

    def __len__(self) -> int:
        return len(self.samples)

    def __getitem__(self, i: int):
        path, label = self.samples[i]
        if path.suffix.lower() in {{".tif", ".tiff"}}:
            import tifffile

            arr = tifffile.imread(str(path))
        else:
            from PIL import Image

            arr = np.asarray(Image.open(path))
        if arr.ndim == 2:
            arr = arr[None, :, :]
        elif arr.ndim == 3 and arr.shape[2] < arr.shape[0]:
            arr = np.moveaxis(arr, 2, 0)  # HWC -> CHW
        img = torch.from_numpy(arr.astype(np.float32))
        if self.transform is not None:
            img = self.transform(img)
        return {{"image": img, "label": label}}


class {class_name}(BenchDataset):
    name = "{dataset_name}"
    task = "classification"
    num_classes = {num_classes}
    multilabel = False
    rgb_bands = {rgb_bands!r}
    split_sizes = {split_sizes!r}
    bands = [
{band_lines}
    ]
    classes = {classes!r}

    @classmethod
    def data_root(cls) -> Path:
        return Path("data") / cls.name

    def get_dataset(self, split, *, partition="default", bands=None, transform=None):
        del partition  # single partition
        specs = self.select_band_specs(bands) if bands else self.bands
        del specs  # all measured bands are stored in-file; band subsetting TODO
        return _FolderDataset(self.data_root(), split, self.classes, transform=transform)
'''


def _identifier(name: str) -> str:
    ident = re.sub(r"[^0-9a-zA-Z_]", "_", name)
    if not ident or ident[0].isdigit() or keyword.iskeyword(ident):
        ident = f"ds_{ident}"
    return ident


def generate_wrapper(
    dataset_name: str,
    class_name: str,
    inspection: Inspection,
    sensor: str,
    band_names: list[str],
    wavelengths: list[float | None],
) -> Wrapper:
    n = inspection.bands
    if len(band_names) != n or len(wavelengths) != n:
        # The caller is a language model, so the error is the only instruction
        # it gets. "must have exactly 19 entries" was true but not actionable —
        # it kept re-sending the informative bands only (the usual cause: a
        # dataset padded with all-zero bands) and burned iterations. Say what
        # was received and exactly how to fix it.
        raise ValueError(
            f"band_names has {len(band_names)} entries and wavelengths has "
            f"{len(wavelengths)}, but this dataset has {n} raw bands and both "
            f"must have exactly {n} — one per band, in band order, INCLUDING "
            f"any all-zero padding bands. Do not drop padding bands: name them "
            f"\"unused\" with a null wavelength and resend all {n}. Which bands "
            f"are worth training on belongs in the normalization note, not in "
            f"the length of these lists."
        )

    band_lines = []
    for i, stat in enumerate(inspection.bandStats):
        wl = wavelengths[i]
        wl_repr = f"{wl:g}" if wl is not None else "None"
        band_lines.append(
            f'        BandSpec("{sensor}", "{band_names[i]}", "{band_names[i]}", '
            f"mean={stat.mean:g}, std={stat.std:g}, min={stat.min:g}, max={stat.max:g}, "
            f"wavelength_um={wl_repr}),"
        )

    classes = sorted(inspection.classBalance) if inspection.classBalance else []
    rgb = [b for b in ("red", "green", "blue") if b in band_names] or band_names[: min(3, n)]

    if set(inspection.splits) & {"train", "val", "test"}:
        split_sizes = {k: inspection.splits.get(k, 0) for k in ("train", "val", "test")}
        split_comment = (
            "Split sizes come from the dataset's train/val/test assignment\n"
            "(split folders, or the splits.json manifest written for auto-fetched\n"
            "chips using a spatial-block split so overlapping chips don't leak)."
        )
    else:
        total = inspection.chips
        split_sizes = {"train": round(total * 0.8), "val": round(total * 0.1),
                       "test": total - round(total * 0.8) - round(total * 0.1)}
        split_comment = (
            "No train/val/test assignment was found — the loader applies a\n"
            "deterministic stable-hash 80/10/10 split (split_sizes are estimates)."
        )

    module_name = _identifier(dataset_name).lower()
    code = _TEMPLATE.format(
        dataset_name=dataset_name,
        module_name=module_name,
        class_name=_identifier(class_name),
        chips=inspection.chips,
        n_bands=n,
        dtype=inspection.dtype,
        structure=inspection.structure,
        split_comment=split_comment,
        num_classes=inspection.numClasses or len(classes) or 2,
        rgb_bands=rgb,
        split_sizes=split_sizes,
        band_lines="\n".join(band_lines),
        classes=classes,
    )
    compile(code, f"{module_name}.py", "exec")  # guarantee valid Python
    return Wrapper(filename=f"datasets/{module_name}.py", code=code, note="")
